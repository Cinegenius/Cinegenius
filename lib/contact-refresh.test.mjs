import test from 'node:test';
import assert from 'node:assert/strict';
import {watchContactRefresh} from './contact-refresh.ts';

test('refresh is visible, event-driven, deduplicated and fully detached after cleanup', t => {
  const browser = Object.assign(new EventTarget(), {document: Object.assign(new EventTarget(), {visibilityState: 'visible'})});
  let now = 1000, reads = 0;
  t.mock.method(Date, 'now', () => now);
  const stop = watchContactRefresh(browser, () => reads++);
  assert.equal(reads, 0, 'registration never starts polling or an extra initial request');
  browser.dispatchEvent(new Event('focus'));
  browser.dispatchEvent(new Event('pageshow'));
  browser.dispatchEvent(new Event('cinegenius:app-resume'));
  browser.document.dispatchEvent(new Event('visibilitychange'));
  assert.equal(reads, 1);
  now += 1000;
  browser.document.visibilityState = 'hidden';
  browser.document.dispatchEvent(new Event('visibilitychange'));
  browser.dispatchEvent(new Event('focus'));
  assert.equal(reads, 1);
  browser.document.visibilityState = 'visible';
  browser.document.dispatchEvent(new Event('visibilitychange'));
  assert.equal(reads, 2);
  now += 1000;
  browser.dispatchEvent(new Event('cinegenius:app-resume'));
  assert.equal(reads, 3);
  stop(); now += 1000;
  for (const name of ['focus', 'pageshow', 'cinegenius:app-resume']) browser.dispatchEvent(new Event(name));
  browser.document.dispatchEvent(new Event('visibilitychange'));
  assert.equal(reads, 3);
});
